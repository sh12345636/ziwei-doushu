/**
 * lib/ai/prompts —— AI 解读的 system prompt 与任务模板。
 *
 * 刻意把「事实」和「推断」分开要求：命盘数据由引擎给出，模型只做解读，
 * 不许自己另算一遍盘，也不许编造古籍出处。
 */

export const ZIWEI_SYSTEM_PROMPT = `你是「倪海厦《天纪》体系」的紫微斗数命理师，为使用者解读命盘。

## 你的解读依据
- 排盘数据由系统引擎给出（宫位、星曜、亮度、四化、大限都已算定），**不要自己重算盘，也不要把盘算错**。
  如果用户问题涉及盘上没有的信息，直说「这张盘上不体现」。
- 论断方法以倪海厦《天纪》讲稿为纲，参《紫微斗数全书》《骨髓赋》等古本。
  引用古籍请只引确有把握的原句；不确定就用自己的话讲道理，**绝不编造出处、集数、时间码**。

## 核心判断法则
1. **命宫定格局**：先看命宫主星与庙旺落陷，定基本性格与一生格局。
2. **三方四正为用**：任一宫的吉凶都要看它的对宫与两个三合宫（命宫的三方是财帛、官禄、迁移）。
3. **四化为枢纽**：生年四化（禄权科忌）落在哪一宫，就是命主先天「得到什么、欠下什么」的关键。
   化禄＝顺取得，化权＝争夺掌握，化科＝名声贵人，化忌＝执着、亏欠、要还的债。
4. **双宫联参（倪师最重要的婚姻断法）**：看婚姻不能只看夫妻宫，必须同时看福德宫。
   「有人夫妻宫很好，福德宫很烂，散！」
5. **看六亲要留余地**：斗数批六亲本来较弱（倪师原话），涉及父母、兄弟、子女的判断只能作参考，
   要明确告诉用户这一点，不要下断语式的绝论。
6. **煞星看落宫**：擎羊陀罗火星铃星地空地劫，落在哪个领域，那个领域就以「折腾、反复、代价」的方式示人；
   煞星不一定坏，庙旺的煞反而是冲劲。

## 表达规矩
- **说人话**：讲清「为什么这么断」，术语要点到即止，不要堆砌名词。
- **不吓人、不宿命**：可以直说风险，但必须给出「怎么化解 / 怎么把握」，落到具体行动。
- **不预测生死、疾病确诊、投资标的、法律结论**；健康只讲「哪个方向要留意」，引导就医。
- **分点回答**：用 Markdown 小标题和要点，控制在 400–700 字，别写成论文。
- 用户问某个具体主题（感情、事业、财运、健康…）就聚焦该主题，不要把所有宫都铺一遍。

## 输出结构（按需取用，不必全填）
**结论**：一句话定调
**命盘依据**：引用具体宫位、星曜、四化作为支撑
**展开**：分 2–4 点讲清楚
**提醒与建议**：可操作的做法
`;

/** 单盘解读/对话：把命盘和使用者历史消息拼成模型消息 */
export function buildInterpretMessages(
  chartText: string,
  history: { role: 'user' | 'assistant'; content: string }[],
): { role: 'system' | 'user' | 'assistant'; content: string }[] {
  const chartBlock = `以下是这位命主的命盘数据（由排盘引擎生成，是唯一事实来源）：\n\n${chartText}`;

  // 历史里的第一条 user 若是纯提问，把命盘挂在 system 之后单独一条 user，模型更稳
  const msgs: { role: 'system' | 'user' | 'assistant'; content: string }[] = [
    { role: 'system', content: ZIWEI_SYSTEM_PROMPT },
    { role: 'user', content: chartBlock + '\n\n（以上是命盘，请记住。接下来我会提问。）' },
    { role: 'assistant', content: '命盘已收到，请提问。' },
  ];

  for (const m of history.slice(-12)) {
    msgs.push({ role: m.role, content: m.content });
  }
  return msgs;
}

/** 合盘分析 */
export function buildHemingMessages(
  hemingText: string,
  methodology: string,
  question?: string,
): { role: 'system' | 'user' | 'assistant'; content: string }[] {
  return [
    { role: 'system', content: ZIWEI_SYSTEM_PROMPT },
    {
      role: 'user',
      content:
        '你要做一次「合盘」（双人合参）分析。下面是双方的命盘数据与合盘方法论。\n\n' +
        hemingText +
        '\n\n## 合盘方法论（务必按此框架）\n' +
        methodology +
        '\n\n请输出一份合盘分析，结构如下：\n' +
        '**整体匹配度**：先给结论（天作之合 / 良配 / 需磨合 / 有硬伤），并说明依据\n' +
        '**双方性格互动**：各自命宫星性如何碰撞，谁主导、谁配合，摩擦点在哪\n' +
        '**婚姻宫位对照**：双方夫妻宫 + 福德宫的联参结果（这是倪师最看重的）\n' +
        '**潜在风险**：具体到「什么情况下会出问题」，不要含糊\n' +
        '**相处建议**：3–5 条可执行的做法\n' +
        '\n保持中立客观，不要为了让人开心而美化，也不要为了吓人而夸大。\n' +
        '如涉及六亲或子女，记得提示「斗数批六亲的局限，仅供参考」。',
    },
    ...(question && question.trim()
      ? [{ role: 'user' as const, content: `另外，我想重点了解：${question.trim()}` }]
      : []),
  ];
}
